print(f"  Células analizadas: {adata.n_obs:,}")
print(f"  Genes totales:      {adata.n_vars:,}")
print(f"  Genes en pseudot.:  {len(sig_genes)}")
print(f"  Objeto final:       {output_h5ad}")
print("══════════════════════════════════════\n")
